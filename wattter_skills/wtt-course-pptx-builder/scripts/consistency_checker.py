#!/usr/bin/env python3
"""Cross-page consistency checker for large-deck parallel generation.

The existing ``svg_quality_checker.py`` validates each page **in isolation**
against ``spec_lock.md`` (colors / fonts / sizes compliance). It has no
cross-page notion. This checker adds the cross-page dimensions that matter
when pages are generated by independent segment sessions in parallel (see
``workflows/parallel-execute.md``):

| Dimension        | Check                                                                  |
|------------------|------------------------------------------------------------------------|
| Color set        | every page's fill/stroke colors ⊆ spec_lock.colors (cross-page report) |
| Font set         | every page's font-family ⊆ spec_lock.typography                       |
| Rhythm distribution| a segment must not be 0% breathing unless genuinely all-dense, and   |
|                  | must not be 100% breathing                                             |
| Breathing grid   | a ``breathing`` page must not use a multi-card grid (multiple parallel |
|                  | rounded containers as primary structure) — static detection           |
| Decor motif      | decorative ``<path d=...>`` motifs appearing on anchor pages should    |
|                  | appear on same-type pages elsewhere (hash approximation)              |

It is a **reporting / gate** tool, not a fixer. Output: per-page drift
score + list of pages exceeding threshold. Exit 1 if any page exceeds the
drift threshold (so it can gate the parallel-execute segment gate).

Usage::

    python3 scripts/consistency_checker.py <project_path>
    python3 scripts/consistency_checker.py <project_path> --segment seg_01
    python3 scripts/consistency_checker.py <project_path> --against-anchors
    python3 scripts/consistency_checker.py <project_path> --threshold 0.3

Reuses ``update_spec.parse_lock`` for spec_lock parsing (same as
``svg_quality_checker.py``). Reads ``generation_state.json`` for segment →
page mapping and anchor list when present.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

try:
    from update_spec import parse_lock as _parse_spec_lock
except ImportError:
    _parse_spec_lock = None

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

HEX_VALUE_RE = re.compile(r"#[0-9A-Fa-f]{3,8}")

# Drift threshold: fraction of checked dimensions a page may fail before
# being flagged. 0.3 = a page failing >30% of applicable checks is flagged.
DEFAULT_THRESHOLD = 0.3


# ---------------------------------------------------------------------------
# Spec_lock allow-sets (mirrors svg_quality_checker._check_spec_lock_drift)
# ---------------------------------------------------------------------------

def _build_allow_sets(lock: dict) -> tuple[set[str], set[str]]:
    """Return (allowed_colors, allowed_fonts) from a parsed spec_lock."""
    allowed_colors: set[str] = set()
    for v in lock.get("colors", {}).values():
        if HEX_VALUE_RE.fullmatch(v):
            allowed_colors.add(v.upper())

    allowed_fonts: set[str] = set()
    typo = lock.get("typography", {})
    if typo:
        default = typo.get("font_family", "").strip()
        if default:
            allowed_fonts.add(_normalize_font_stack(default))
        for k, v in typo.items():
            if k == "font_family" or not k.endswith("_family"):
                continue
            v_clean = v.strip()
            if not v_clean or v_clean.lower().startswith("same as"):
                continue
            allowed_fonts.add(_normalize_font_stack(v_clean))
    return allowed_colors, allowed_fonts


def _normalize_font_stack(stack: str) -> str:
    """Normalize a font-family stack for comparison (lowercase, strip quotes/space)."""
    parts = re.split(r"[,，]", stack)
    cleaned = []
    for p in parts:
        p = p.strip().strip("\"'").strip().lower()
        if p:
            cleaned.append(p)
    return "|".join(cleaned)


# ---------------------------------------------------------------------------
# Per-page extraction
# ---------------------------------------------------------------------------

def _page_colors(content: str) -> set[str]:
    out: set[str] = set()
    for attr in ("fill", "stroke", "stop-color"):
        for m in re.finditer(rf'\b{attr}\s*=\s*["\'](#[0-9A-Fa-f]{{3,8}})["\']', content):
            out.add(m.group(1).upper())
    return out


def _page_fonts(content: str) -> set[str]:
    out: set[str] = set()
    for m in re.finditer(r'font-family\s*=\s*(["\'])(.*?)\1', content):
        out.add(_normalize_font_stack(m.group(2)))
    return out


def _decor_motifs(content: str) -> set[str]:
    """Hash decorative path d-strings as motif fingerprints.

    Only ``<path d=...>`` with >= 4 coordinate pairs counts as a decorative
    motif (short lines/connector arrows are noise). Hash to keep output
    stable and compact.
    """
    out: set[str] = set()
    for m in re.finditer(r'<path\b[^>]*\bd\s*=\s*["\']([^"\']+)["\']', content):
        d = m.group(1)
        # count coordinate-ish tokens
        coords = len(re.findall(r"[-\d.]+", d))
        if coords >= 8:
            out.add(hashlib.md5(d.encode("utf-8")).hexdigest()[:10])
    return out


def _rounded_rect_count(content: str) -> int:
    """Count rounded rectangles (rx/ry present) — proxy for card containers."""
    count = 0
    for m in re.finditer(r"<rect\b[^>]*>", content):
        if re.search(r"\brx\s*=", m.group(0)) or re.search(r"\bry\s*=", m.group(0)):
            count += 1
    return count


# ---------------------------------------------------------------------------
# Page id / rhythm helpers
# ---------------------------------------------------------------------------

def _page_id_from_svg(svg_path: Path) -> str:
    """Extract P<NN> from filename like ``03_content.svg`` → ``P03``."""
    m = re.match(r"^(\d+)", svg_path.stem)
    return f"P{int(m.group(1)):02d}" if m else svg_path.stem


def _rhythm_for_page(lock: dict, page_id: str) -> str | None:
    rhythm = lock.get("page_rhythm", {})
    return rhythm.get(page_id)


def _load_generation_state(project: Path) -> dict | None:
    p = project / "generation_state.json"
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def _segment_pages(state: dict | None, seg_id: str | None) -> list[str] | None:
    if not state or not seg_id:
        return None
    seg = next((s for s in state.get("segments", []) if s["id"] == seg_id), None)
    return seg["pages"] if seg else None


# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------

def check_page(svg_path: Path, lock: dict, allow_colors: set[str],
               allow_fonts: set[str]) -> dict:
    """Run all applicable checks on one page. Returns a result dict."""
    raw = svg_path.read_text(encoding="utf-8")
    # HTML-unescape per extracted value (not globally — global unescape
    # corrupts attribute boundaries when font stacks embed &quot;).
    content = raw
    page_id = _page_id_from_svg(svg_path)

    checks: list[tuple[str, bool, str]] = []  # (name, passed, detail)

    # 1. color drift
    page_colors = _page_colors(content)
    color_drift = page_colors - allow_colors if allow_colors else set()
    checks.append(("colors", not color_drift,
                   f"drift: {sorted(color_drift)}" if color_drift else "ok"))

    # 2. font drift — unescape each captured stack before normalizing
    page_fonts: set[str] = set()
    for m in re.finditer(r'font-family\s*=\s*(["\'])(.*?)\1', content):
        page_fonts.add(_normalize_font_stack(html.unescape(m.group(2))))
    font_drift = page_fonts - allow_fonts if allow_fonts else set()
    checks.append(("fonts", not font_drift,
                   f"drift: {sorted(font_drift)}" if font_drift else "ok"))

    # 3. breathing page must not be a multi-card grid
    rhythm = _rhythm_for_page(lock, page_id)
    if rhythm == "breathing":
        rr = _rounded_rect_count(content)
        # >2 rounded rects on a breathing page ≈ multi-card grid
        checks.append(("breathing-no-grid", rr <= 2,
                       f"{rr} rounded rects (≤2 allowed)" if rr > 2 else "ok"))
    # anchor pages: no grid check (structural pages legitimately use templates)

    # 4. decor motifs (reported, not failed — cross-page aggregation below)
    motifs = _decor_motifs(content)

    failed = sum(1 for _, p, _ in checks if not p)
    applicable = len(checks)
    score = failed / applicable if applicable else 0.0
    return {
        "page": page_id,
        "file": svg_path.name,
        "rhythm": rhythm,
        "checks": checks,
        "score": score,
        "failed_count": failed,
        "motifs": motifs,
    }


def check_rhythm_distribution(results: list[dict], lock: dict) -> list[dict]:
    """Segment/deck-level rhythm distribution check. Returns findings."""
    findings: list[dict] = []
    rhythm_counter = Counter(r["rhythm"] for r in results if r["rhythm"])
    total = sum(rhythm_counter.values())
    if total == 0:
        return findings
    breathing_pct = rhythm_counter.get("breathing", 0) / total
    if breathing_pct == 0.0:
        # all-dense is legitimate for data decks — only flag as info
        findings.append({"check": "rhythm-distribution",
                         "severity": "info",
                         "msg": f"0% breathing across {total} pages — "
                                "legitimate for all-dense data decks, verify intent"})
    elif breathing_pct == 1.0:
        findings.append({"check": "rhythm-distribution",
                         "severity": "warning",
                         "msg": f"100% breathing across {total} pages — "
                                "no structural/dense pages, likely rhythm error"})
    return findings


def check_motif_continuity(results: list[dict], anchor_pages: set[str]) -> list[dict]:
    """Decorative motifs on anchors should recur on non-anchor pages.

    A motif that appears on >=1 anchor but on <10% of non-anchor pages is
    'lost' — flag as info (decorative continuity is soft).
    """
    findings: list[dict] = []
    if not anchor_pages:
        return findings
    anchor_motifs: set[str] = set()
    for r in results:
        if r["page"] in anchor_pages or r["file"] in anchor_pages:
            anchor_motifs |= r["motifs"]
    if not anchor_motifs:
        return findings
    non_anchor = [r for r in results
                  if r["page"] not in anchor_pages and r["file"] not in anchor_pages]
    if not non_anchor:
        return findings
    motif_page_count = sum(1 for r in non_anchor if r["motifs"] & anchor_motifs)
    pct = motif_page_count / len(non_anchor)
    if pct < 0.10:
        findings.append({"check": "motif-continuity",
                         "severity": "info",
                         "msg": f"anchor decor motifs appear on only "
                                f"{motif_page_count}/{len(non_anchor)} non-anchor "
                                f"pages ({pct:.0%}) — decorative continuity may be lost"})
    return findings


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Cross-page consistency checker for parallel-generated decks."
    )
    parser.add_argument("project", help="project path (contains spec_lock.md + svg_output/)")
    parser.add_argument("--segment", default=None,
                        help="check only pages in this segment (reads generation_state.json)")
    parser.add_argument("--against-anchors", action="store_true",
                        help="run motif-continuity check against approved anchor pages")
    parser.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD,
                        help=f"drift score threshold for flagging a page (default {DEFAULT_THRESHOLD})")
    parser.add_argument("--json", action="store_true", help="emit JSON instead of text")
    args = parser.parse_args()

    project = Path(args.project)
    lock_path = project / "spec_lock.md"
    if not lock_path.exists():
        print(f"Error: {lock_path} not found", file=sys.stderr)
        return 1
    if _parse_spec_lock is None:
        print("Error: update_spec.parse_lock unavailable (import failed)", file=sys.stderr)
        return 1

    lock = _parse_spec_lock(lock_path)
    allow_colors, allow_fonts = _build_allow_sets(lock)

    svg_output = project / "svg_output"
    if not svg_output.exists():
        print(f"Error: {svg_output} not found", file=sys.stderr)
        return 1

    state = _load_generation_state(project)
    seg_pages = _segment_pages(state, args.segment)

    # collect SVGs to check
    svgs = sorted(svg_output.glob("*.svg"))
    if seg_pages is not None:
        seg_set = set(seg_pages)
        svgs = [s for s in svgs if _page_id_from_svg(s) in seg_set]
    if not svgs:
        print(f"[consistency] no SVGs to check in {svg_output}", file=sys.stderr)
        return 1

    results = [check_page(s, lock, allow_colors, allow_fonts) for s in svgs]

    # anchor set for motif continuity
    anchor_pages: set[str] = set()
    if args.against_anchors and state:
        anchor_pages = set(state.get("anchors", {}).get("pages", []))

    deck_findings = check_rhythm_distribution(results, lock)
    if args.against_anchors:
        deck_findings += check_motif_continuity(results, anchor_pages)

    flagged = [r for r in results if r["score"] > args.threshold]

    if args.json:
        out = {
            "project": project.name,
            "segment": args.segment,
            "pages_checked": len(results),
            "flagged": [{"page": r["page"], "file": r["file"],
                         "score": round(r["score"], 2),
                         "failed_checks": [c[0] for c in r["checks"] if not c[1]]}
                        for r in flagged],
            "deck_findings": deck_findings,
            "threshold": args.threshold,
        }
        print(json.dumps(out, ensure_ascii=False, indent=2))
    else:
        print(f"[consistency] {project.name}: checked {len(results)} page(s)"
              + (f" in segment {args.segment}" if args.segment else ""))
        for r in results:
            status = "FLAG" if r["score"] > args.threshold else "ok"
            fails = [c[0] for c in r["checks"] if not c[1]]
            print(f"  [{status}] {r['page']} ({r['file']}) score={r['score']:.2f}"
                  + (f"  fails={fails}" if fails else ""))
        if deck_findings:
            print("\ndeck-level findings:")
            for f in deck_findings:
                print(f"  [{f['severity']}] {f['check']}: {f['msg']}")
        print(f"\nflagged: {len(flagged)}/{len(results)} (threshold {args.threshold})")

    return 1 if flagged else 0


if __name__ == "__main__":
    sys.exit(main())
